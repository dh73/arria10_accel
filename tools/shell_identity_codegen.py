"""Deterministic source/build identities and retained output associations.

No device access, physical admission, signature, or load observation is provided.
The build owner must pass the emitted ROM into the declared synthesis recipe.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import tempfile

import kernel_abi
import kernel_executor_codegen as abi_codegen

U32 = (1 << 32) - 1
U64 = (1 << 64) - 1
DOMAIN = b"a10-shell-build-v1\0"
AUTO_INPUT = "rtl/shell_identity_v1.sv"
TOOL_FILES = {
    "shell_identity_codegen.py": Path(__file__),
    "kernel_abi.py": Path(kernel_abi.__file__),
    "kernel_executor_codegen.py": Path(abi_codegen.__file__),
}


def require(ok, message):
    if not ok:
        raise ValueError(message)


def keys(value, expected, name):
    require(type(value) is dict and set(value) == set(expected), "unsupported " + name)


def uint(value, maximum):
    return type(value) is int and 0 <= value <= maximum


def digest(value):
    return type(value) is str and re.fullmatch(r"[0-9a-f]{64}", value) is not None


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=True, allow_nan=False).encode("ascii")


def encoded(value):
    return canonical(value) + b"\n"


def no_constant(value):
    raise ValueError("non-finite JSON number: " + value)


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"),
                      object_pairs_hook=abi_codegen.unique_object,
                      parse_constant=no_constant)


def relative(value):
    require(type(value) is str and value and "\\" not in value and
            all(32 <= ord(c) < 127 for c in value) and
            not PurePosixPath(value).is_absolute() and
            all(p not in ("", ".", "..") for p in value.split("/")),
            "invalid relative input path")
    return value


def input_file(root, name):
    path = (root / relative(name)).resolve(strict=True)
    require(path.is_relative_to(root) and path.is_file(), "input escapes root or is not a file")
    return path


def file_hash(path):
    h = hashlib.sha256()
    length = 0
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
            length += len(chunk)
    return h.hexdigest(), length


def validate_plan(plan, cra_bytes):
    keys(plan, ("schema", "management", "cra", "resources", "inputs", "recipe"), "plan")
    require(type(plan["schema"]) is int and plan["schema"] == 1, "unsupported plan schema")
    require(type(plan["resources"]) is list and plan["resources"], "missing resources")
    resources = {}
    for resource in plan["resources"]:
        keys(resource, ("space", "bytes"), "resource")
        space, length = resource["space"], resource["bytes"]
        require(uint(space, U32) and uint(length, U64) and length != 0 and
                space not in resources, "invalid/duplicate resource")
        resources[space] = length
    intervals = []
    for field, length, alignment in (("management", 256, 4), ("cra", cra_bytes, 8)):
        item = plan[field]
        keys(item, ("space", "offset"), field)
        space, offset = item["space"], item["offset"]
        require(uint(space, U32) and space in resources and uint(offset, U64) and
                uint(length, U64) and length != 0 and offset % alignment == 0,
                "invalid aperture")
        require(length <= resources[space] and offset <= resources[space] - length,
                "out-of-bounds/overflowing aperture")
        intervals.append((space, offset, offset + length))
    a, b = intervals
    require(a[0] != b[0] or a[2] <= b[1] or b[2] <= a[1], "overlapping apertures")
    require(type(plan["inputs"]) is list and plan["inputs"], "missing synthesis inputs")
    names = [relative(name) for name in plan["inputs"]]
    require(len(names) == len(set(names)), "duplicate input path")
    require(type(plan["recipe"]) is str and plan["recipe"].strip(), "missing recipe identity")
    return {"schema": 1, "management": dict(plan["management"]), "cra": dict(plan["cra"]),
            "resources": [{"space": k, "bytes": v} for k, v in sorted(resources.items())],
            "inputs": sorted(names), "recipe": plan["recipe"]}


def render(manifest):
    plan = manifest["plan"]
    values = {
        "mgmt_space": plan["management"]["space"],
        "cra_space": plan["cra"]["space"],
        "mgmt_base": plan["management"]["offset"],
        "cra_base": plan["cra"]["offset"],
        "cra_bytes": manifest["abi"]["cra_aperture_bytes"],
    }
    sv = ["// Generated by shell_identity_codegen.py; compile into the new shell."]
    cpp = ["#pragma once", "#include <array>", "#include <cstdint>",
           "namespace asus::a10::image::generated {"]
    for label in ("source", "build"):
        raw = bytes.fromhex(manifest[label + "_sha256"])
        sv.append("localparam logic [255:0] ID_%s = 256'h%s;" %
                  (label.upper(), raw[::-1].hex()))
        cpp.append("inline constexpr std::array<std::uint8_t, 32> %s_sha256{{%s}};" %
                   (label, ",".join("0x%02x" % byte for byte in raw)))
    for label, value in values.items():
        width = 32 if label.endswith("space") else 64
        sv.append("localparam logic [%d:0] ID_%s = %d'd%d;" %
                  (width - 1, label.upper(), width, value))
        cpp.append("inline constexpr std::uint%d_t %s = %d%s;" %
                   (width, label, value, "U" if width == 32 else "ULL"))
    cpp.append("}")
    return {"shell_identity_params.svh": ("\n".join(sv) + "\n").encode("ascii"),
            "shell_identity_expected.hpp": ("\n".join(cpp) + "\n").encode("ascii")}


def write_new(path, data):
    """Publish one complete file without replacing an existing destination."""
    path = Path(path)
    fd, temporary = tempfile.mkstemp(prefix=".identity-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.link(temporary, path)
    finally:
        os.unlink(temporary)


def prepare(source, plan_path, root, out):
    source, root = Path(source).resolve(strict=True), Path(root).resolve(strict=True)
    out = Path(out).absolute()
    require(not out.exists() and not out.is_symlink(), "output must be a new directory")
    require(not out.resolve().is_relative_to(source), "output is inside source snapshot")
    abi = abi_codegen.source_contract(kernel_abi.extract(source))
    plan = validate_plan(read_json(plan_path), abi["cra_aperture_bytes"])
    inputs, resolved = {}, set()
    for name in sorted(set(plan["inputs"]) | {AUTO_INPUT}):
        path = input_file(root, name)
        require(path not in resolved, "aliased input paths")
        resolved.add(path)
        inputs[name] = file_hash(path)[0]
    # Recheck the extractor's actual six files before publishing any result.
    for name, expected in abi["source_sha256"].items():
        require(file_hash(input_file(source, name))[0] == expected, "source changed during extraction")
    manifest = {"schema": 1, "kind": "a10-shell-build-v1", "abi": abi, "plan": plan,
                "inputs": inputs, "tools": {k: file_hash(v)[0] for k, v in TOOL_FILES.items()},
                "source_sha256": abi_codegen.source_contract_sha256(abi)}
    manifest["build_sha256"] = hashlib.sha256(DOMAIN + canonical(manifest)).hexdigest()
    outputs = render(manifest)
    out.mkdir(parents=False, exist_ok=False)
    for name, data in outputs.items():
        write_new(out / name, data)
    write_new(out / "prepared.json", encoded(manifest))  # Published last.
    return manifest


def load_prepared(directory):
    directory = Path(directory)
    path = directory / "prepared.json"
    manifest = read_json(path)
    keys(manifest, ("schema", "kind", "abi", "plan", "inputs", "tools",
                    "source_sha256", "build_sha256"), "prepared manifest")
    require(type(manifest["schema"]) is int and manifest["schema"] == 1 and
            manifest["kind"] == "a10-shell-build-v1", "unsupported prepared schema")
    abi = abi_codegen.source_contract(manifest["abi"])
    require(abi == manifest["abi"], "noncanonical source contract")
    require(validate_plan(manifest["plan"], abi["cra_aperture_bytes"]) == manifest["plan"],
            "noncanonical plan")
    keys(manifest["inputs"], set(manifest["plan"]["inputs"]) | {AUTO_INPUT}, "input inventory")
    keys(manifest["tools"], TOOL_FILES, "generator inventory")
    require(all(digest(v) for v in manifest["inputs"].values()) and
            all(digest(v) for v in manifest["tools"].values()), "invalid input digest")
    require(manifest["source_sha256"] == abi_codegen.source_contract_sha256(abi),
            "false source identity")
    core = {k: v for k, v in manifest.items() if k != "build_sha256"}
    require(manifest["build_sha256"] == hashlib.sha256(DOMAIN + canonical(core)).hexdigest(),
            "false build identity")
    require(path.read_bytes() == encoded(manifest), "noncanonical prepared bytes")
    for name, data in render(manifest).items():
        require((directory / name).read_bytes() == data, "modified embedded/host identity")
    return manifest


def output_record(prepared_dir, bitstream_path):
    manifest = load_prepared(prepared_dir)
    bitstream = Path(bitstream_path).resolve(strict=True)
    require(bitstream.is_file(), "bitstream is not a file")
    require(not bitstream.is_relative_to(Path(prepared_dir).resolve()),
            "bitstream must be a separate synthesis output")
    sha, length = file_hash(bitstream)
    require(length != 0, "empty bitstream")
    return {"schema": 1, "kind": "a10-shell-output-v1",
            "scope": "retained build association; load not observed",
            "source_sha256": manifest["source_sha256"], "build_sha256": manifest["build_sha256"],
            "prepared_sha256": hashlib.sha256(encoded(manifest)).hexdigest(),
            "bitstream_sha256": sha, "bitstream_bytes": length}


def bind(prepared_dir, bitstream_path, record_path):
    record = output_record(prepared_dir, bitstream_path)
    write_new(record_path, encoded(record))
    return record


def check(prepared_dir, bitstream_path, record_path):
    expected = output_record(prepared_dir, bitstream_path)
    actual = read_json(record_path)
    require(type(actual) is dict and canonical(actual) == canonical(expected),
            "output/source/build association mismatch")
    return expected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    p = commands.add_parser("prepare")
    for name in ("source", "plan", "root", "out"):
        p.add_argument("--" + name, type=Path, required=True)
    for command in ("bind", "check"):
        p = commands.add_parser(command)
        p.add_argument("--prepared", type=Path, required=True)
        p.add_argument("--bitstream", type=Path, required=True)
        p.add_argument("--output" if command == "bind" else "--record", type=Path, required=True)
    args = parser.parse_args()
    if args.command == "prepare":
        prepare(args.source, args.plan, args.root, args.out)
    elif args.command == "bind":
        bind(args.prepared, args.bitstream, args.output)
    else:
        check(args.prepared, args.bitstream, args.record)
    print("A10_IDENTITY_%s_PASS" % args.command.upper())


if __name__ == "__main__":
    main()
